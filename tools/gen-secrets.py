#!/usr/bin/env python3
"""Generate docs/SECRETS.md and the ExternalSecret manifests from secrets/catalog.yaml.

  python3 tools/gen-secrets.py           write the files
  python3 tools/gen-secrets.py --check   exit 1 if a generated file differs (used in CI)
"""
import sys
import yaml

root = __file__.rsplit("/tools/", 1)[0] if "/tools/" in __file__ else "."
cat = yaml.safe_load(open(f"{root}/secrets/catalog.yaml"))


def secrets_md():
    out = [cat["header"]]
    for s in cat["secrets"]:
        out.append(f"## `{s['name']}`{s.get('title_suffix', '')}\n\n| Key | Required | Note |\n|---|---|---|\n")
        for k in s["keys"]:
            out.append(f"| `{k['key']}` | {k['required']} | {k['note']} |\n".replace("|  |", "|  |"))
        out.append("\n")
    out.append(cat["footer"])
    return "".join(out)


def externalsecrets(group):
    docs = []
    for s in cat["secrets"]:
        if s.get("external", "base") != group:
            continue
        n = s["name"]
        if n == "dockerhub-pull":
            target = (f"  target:\n    name: {n}\n    creationPolicy: Owner\n    template:\n      type: kubernetes.io/dockerconfigjson\n"
                      "      data:\n        .dockerconfigjson: '{{ index . \".dockerconfigjson\" }}'\n")
        else:
            target = f"  target:\n    name: {n}\n    creationPolicy: Owner\n"
        docs.append(f"""apiVersion: external-secrets.io/v1
kind: ExternalSecret
metadata:
  name: {n}
  annotations:
    argocd.argoproj.io/sync-wave: "0"
spec:
  refreshInterval: 1h
  secretStoreRef: {{kind: ClusterSecretStore, name: kuasar}}
{target}  dataFrom:
  - extract:
      key: kuasar/ENV/{n}
""")
    return docs


outputs = {
    "docs/SECRETS.md": secrets_md(),
    "components/external-secrets/externalsecrets.yaml": (
        "# GENERATED by tools/gen-secrets.py from secrets/catalog.yaml: do not edit by hand.\n"
        "# One remote secret per Kubernetes Secret, holding a JSON object whose keys are the Secret keys.\n"
        "# Remote key: kuasar/<env>/<secret name>   (env comes from the ConfigMap in env-configmap.yaml, set by the overlay).\n---\n"
        + "---\n".join(externalsecrets("base"))
    ),
    "components/observability-external-secrets/externalsecrets.yaml": (
        "# GENERATED by tools/gen-secrets.py from secrets/catalog.yaml: do not edit by hand.\n"
        "# Only used together with components/external-secrets (same remote key convention and the same env replacement).\n---\n"
        + "---\n".join(externalsecrets("observability"))
    ),
}

bad = []
for path, text in outputs.items():
    full = f"{root}/{path}"
    try:
        current = open(full).read()
    except FileNotFoundError:
        current = None
    if "--check" in sys.argv:
        if current != text:
            bad.append(path)
    else:
        open(full, "w").write(text)
        print("wrote", path)
if bad:
    print("out of date (run python3 tools/gen-secrets.py):", *bad, sep="\n  ")
    sys.exit(1)
